async function main() {
  console.log("Seeding WHT rules...");

  for (const rule of rules) {
    await db
      .insert(whtRules)
      .values({
        ruleKey: rule.ruleKey,
        section: rule.section,
        subSection: rule.subSection ?? null,
        description: rule.description,
        recipientType: rule.recipientType,
        rateFiler: rule.rateFiler.toString(),
        rateNonFiler: rule.rateNonFiler.toString(),
        thresholdAmount: rule.thresholdAmount?.toString() ?? "0",
        isTiered: rule.isTiered ?? false,
        tieredRates: rule.tieredRates ?? null,
        usesSlabRates: rule.usesSlabRates ?? false,
        keywords: rule.keywords ?? [],
        active: true,
        notes: rule.notes ?? null,
      })
      .onConflictDoNothing({ target: whtRules.ruleKey });
  }

  console.log(`✓ Seeded ${rules.length} WHT rules`);
  process.exit(0);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
